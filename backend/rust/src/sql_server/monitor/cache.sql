SELECT CONVERT(varchar(32), SUM(CASE WHEN type = 'MEMORYCLERK_SQLBUFFERPOOL' THEN pages_kb END) * 1024) AS buffer_pool,
       CONVERT(varchar(32), SUM(CASE WHEN type IN ('CACHESTORE_SQLCP', 'CACHESTORE_OBJCP') THEN pages_kb END) * 1024) AS plan_cache
FROM sys.dm_os_memory_clerks
WHERE type IN ('MEMORYCLERK_SQLBUFFERPOOL', 'CACHESTORE_SQLCP', 'CACHESTORE_OBJCP')
